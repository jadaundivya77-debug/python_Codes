#Errors are the problems that occur during the execution of a program. There are mainly 3 types of errors in python:
#1. Syntax Errors
#2. Runtime Errors
#3. Logical Errors
#syntax Errors: These are the errors that occur when the python parser is unable to understand a line of code due to incorrect syntax.
#   For example, missing a colon at the end of a for loop or if statement will result in a syntax error.
#Runtime Errors: These are the errors that occur during the execution of a program. They are also known as exceptions. For example, dividing a number by zero will result in a runtime error.
#Logical Errors: These are the errors that occur when the program runs without any syntax or runtime



